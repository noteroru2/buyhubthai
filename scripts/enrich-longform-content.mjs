function renderSection(heading, paragraphs, list = '') {
  const parts = [`## ${heading}`, ...paragraphs.map((paragraph) => paragraph.trim())];
  if (list) parts.push(list.trim());
  return parts.join('\n\n');
}

function markdownList(items) {
  return items.map((item) => `- ${item}`).join('\n');
}

function markdownLinks(items) {
  return items.map(([label, href]) => `- [${label}](${href})`).join('\n');
}

function joinThaiList(items) {
  if (!items.length) return '';
  if (items.length === 1) return items[0];
  if (items.length === 2) return `${items[0]} และ ${items[1]}`;
  return `${items.slice(0, -1).join(', ')} และ ${items.at(-1)}`;
}

function extractMeta(frontmatter) {
  return {
    title: extractScalar(frontmatter, 'title'),
    description: extractScalar(frontmatter, 'description'),
    serviceName: extractScalar(frontmatter, 'serviceName'),
    province: extractScalar(frontmatter, 'province'),
    tags: extractArray(frontmatter, 'tags'),
    faqs: extractFaqs(frontmatter)
  };
}

function extractScalar(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
  if (!match) return null;
  return unquote(match[1].trim());
}

function extractArray(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*\\[(.*)\\]\\s*$`, 'm'));
  if (!match) return [];
  return match[1]
    .split(',')
    .map((item) => unquote(item.trim()))
    .filter(Boolean);
}

function extractFaqs(frontmatter) {
  const lines = frontmatter.split(/\r?\n/);
  const faqs = [];
  let current = null;

  for (const line of lines) {
    const questionMatch = line.match(/^\s*-\s*question:\s*(.+)$/);
    if (questionMatch) {
      if (current?.question && current?.answer) faqs.push(current);
      current = { question: unquote(questionMatch[1].trim()), answer: '' };
      continue;
    }

    const answerMatch = line.match(/^\s*answer:\s*(.+)$/);
    if (answerMatch && current) {
      current.answer = unquote(answerMatch[1].trim());
    }
  }

  if (current?.question && current?.answer) faqs.push(current);
  return faqs;
}

function unquote(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function splitFrontmatter(source) {
  if (!source.startsWith('---')) {
    return { frontmatter: '', body: source };
  }

  const endIndex = source.indexOf('\n---', 3);
  if (endIndex === -1) {
    return { frontmatter: '', body: source };
  }

  const frontmatter = source.slice(3, endIndex).replace(/^\n/, '');
  const body = source.slice(endIndex + 4).replace(/^\r?\n/, '');
  return { frontmatter, body };
}

function stripGeneratedBlock(body) {
  const pattern = new RegExp(`${escapeRegExp(START_MARKER)}[\\s\\S]*?${escapeRegExp(END_MARKER)}`, 'g');
  return body.replace(pattern, '').trim();
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function countWords(markdown) {
  const text = markdown
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`[^`]*`/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]+\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/^>\s?/gm, '')
    .replace(/^#+\s?/gm, '')
    .replace(/[*_~|-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  let total = 0;
  for (const segment of segmenter.segment(text)) {
    if (segment.isWordLike) total += 1;
  }
  return total;
}

async function walkMarkdown(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walkMarkdown(fullPath)));
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(fullPath);
    }
  }

  return files.sort((a, b) => a.localeCompare(b, 'th'));
}

