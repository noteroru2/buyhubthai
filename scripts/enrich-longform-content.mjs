async function main() {
  const groups = [
    { kind: 'sell', dir: path.join(REPO_ROOT, 'src', 'content', 'sell') },
    { kind: 'areas', dir: path.join(REPO_ROOT, 'src', 'content', 'areas') },
    { kind: 'blog', dir: path.join(REPO_ROOT, 'src', 'content', 'blog') }
  ].filter((group) => REQUESTED_GROUPS.size === 0 || REQUESTED_GROUPS.has(group.kind));

  const results = [];

  for (const group of groups) {
    const files = await walkMarkdown(group.dir);
    for (const file of files) {
      const source = await fs.readFile(file, 'utf8');
      const { frontmatter, body } = splitFrontmatter(source);
      const cleanBody = stripGeneratedBlock(body).trim();
      const meta = extractMeta(frontmatter);
      const context = buildContext(group.kind, file, meta);
      const normalizedBody = group.kind === 'blog' ? replaceBlogMidCta(cleanBody, context) : cleanBody;
      const nextBody = enrichBody(group.kind, normalizedBody, context);
      const nextSource = `---\n${frontmatter.trim()}\n---\n\n${nextBody.trim()}\n`;
      await fs.writeFile(file, nextSource, 'utf8');

      results.push({
        file: path.relative(REPO_ROOT, file),
        before: countWords(normalizedBody),
        after: countWords(nextBody)
      });
    }
  }

  const summary = results.reduce(
    (acc, item) => {
      acc.files += 1;
      acc.min = Math.min(acc.min, item.after);
      acc.max = Math.max(acc.max, item.after);
      if (item.after >= TARGET_WORDS) acc.meetingTarget += 1;
      return acc;
    },
    { files: 0, meetingTarget: 0, min: Number.POSITIVE_INFINITY, max: 0 }
  );

  for (const item of results) {
    console.log(`${item.file}: ${item.before} -> ${item.after} words`);
  }

  console.log(
    `\nLong-form enrichment complete: ${summary.files} files, ${summary.meetingTarget}/${summary.files} meeting ${TARGET_WORDS}+ words, range ${summary.min}-${summary.max} words.`
  );
}

function enrichBody(kind, body, context) {
  const sections = kind === 'sell' ? buildSellSections(context) : kind === 'areas' ? buildAreaSections(context) : buildBlogSections(context);
  let generated = [];
  let current = countWords(body);

  if (current >= TARGET_WORDS) {
    return body;
  }

  for (const section of sections) {
    if (current >= TARGET_WORDS) break;
    generated.push(section);
    current = countWords(`${body}\n\n${generated.join('\n\n')}`);
  }

  let extraIndex = 1;
  while (current < TARGET_WORDS) {
    const filler = buildFallbackSection(kind, context, extraIndex);
    generated.push(filler);
    current = countWords(`${body}\n\n${generated.join('\n\n')}`);
    extraIndex += 1;
  }

  if (generated.length === 0) {
    return body;
  }

  return `${body}\n\n${START_MARKER}\n\n${generated.join('\n\n')}\n\n${END_MARKER}`;
}

