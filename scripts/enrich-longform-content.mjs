function replaceBlogMidCta(body, context) {
  const nextSection = buildBlogMidCtaSection(context);
  const pattern = /## สรุปและ CTA[\s\S]*$/u;
  return pattern.test(body) ? body.replace(pattern, nextSection).trim() : `${body.trim()}\n\n${nextSection}`;
}

