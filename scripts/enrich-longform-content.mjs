function getSellGroupKey(slug, topic) {
  const text = `${slug} ${topic}`.toLowerCase();
  if (/(iphone|ipad|macbook)/.test(text)) return 'apple';
  if (/(airpods|apple-watch|apple-pencil)/.test(text)) return 'audioWearable';
  if (/(notebook|macbook)/.test(text)) return 'notebook';
  if (/(desktop-pc|gaming-pc|pc-assembled|gpu|monitor|คอมพิวเตอร์|การ์ดจอ|จอคอม|คอมเกมมิ่ง)/.test(text)) return 'pc';
  if (/(mobile-phone|tablet|samsung|มือถือ|แท็บเล็ต)/.test(text)) return 'android';
  if (/camera|กล้อง/.test(text)) return 'camera';
  if (/(game-console|playstation|nintendo-switch|gaming-gear|เครื่องเกม)/.test(text)) return 'gaming';
  if (/(corporate-it|office-it|printer|it-accessories|คอมบริษัท|เครื่องปริ้น|สำนักงาน)/.test(text)) return 'office';
  return 'general';
}

function getBlogGroupKey(slug, title, tags, focusTopic) {
  return getSellGroupKey(slug, `${title} ${focusTopic} ${tags.join(' ')}`);
}

