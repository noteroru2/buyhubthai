function detectFocusTopic(title, tags) {
  const joined = `${title} ${tags.join(' ')}`.toLowerCase();
  if (joined.includes('iphone')) return 'iPhone';
  if (joined.includes('ipad')) return 'iPad';
  if (joined.includes('macbook')) return 'MacBook';
  if (joined.includes('airpods')) return 'AirPods';
  if (joined.includes('apple pencil')) return 'Apple Pencil';
  if (joined.includes('apple watch')) return 'Apple Watch';
  if (joined.includes('คอมบริษัท')) return 'คอมบริษัทและอุปกรณ์สำนักงาน IT';
  if (joined.includes('เครื่องปริ้น') || joined.includes('printer')) return 'เครื่องปริ้น';
  if (joined.includes('อุปกรณ์สำนักงาน')) return 'อุปกรณ์สำนักงาน IT';
  if (joined.includes('โน๊ตบุ๊ค') || joined.includes('notebook')) return 'โน๊ตบุ๊ค';
  if (joined.includes('คอมเกมมิ่ง') || joined.includes('gaming pc')) return 'คอมเกมมิ่ง';
  if (joined.includes('การ์ดจอ') || joined.includes('gpu')) return 'การ์ดจอ';
  if (joined.includes('จอคอม') || joined.includes('monitor')) return 'จอคอม';
  if (joined.includes('แท็บเล็ต') || joined.includes('tablet')) return joined.includes('android') ? 'แท็บเล็ต Android' : 'แท็บเล็ต';
  if (joined.includes('อุปกรณ์-it') || joined.includes('อุปกรณ์ it')) return 'อุปกรณ์ IT';
  if (joined.includes('คอม') || joined.includes('pc')) return 'คอมพิวเตอร์หรืออุปกรณ์พีซี';
  if (joined.includes('switch')) return 'Nintendo Switch';
  if (joined.includes('playstation')) return 'PlayStation';
  if (joined.includes('กล้อง') || joined.includes('camera')) return 'กล้อง';
  if (joined.includes('samsung')) return 'Samsung';
  return 'สินค้าไอที';
}

