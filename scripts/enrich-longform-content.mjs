function buildBlogFaqThemes(context) {
  return (context.faqs ?? [])
    .filter((faq) => faq.question && faq.answer)
    .map((faq) => {
      const cleanQuestion = normalizeFaqQuestion(faq.question);
      const intent = getFaqIntent(cleanQuestion);
      const list = getFaqThemeListByIntent(intent, context);
      return {
        heading: buildFaqHeading(cleanQuestion),
        paragraphs: [faq.answer.trim(), buildFaqFollowUpParagraph(context, cleanQuestion, intent)],
        list
      };
    });
}

function normalizeFaqQuestion(question) {
  return question.replace(/\s*\(ตอบสั้น\s*ๆ\)\s*$/u, '').replace(/\?+$/u, '').trim();
}

function buildFaqHeading(question) {
  return `ขยายคำตอบ: ${question}`;
}

function getFaqIntent(question) {
  const text = question.toLowerCase();
  if (/(ส่งข้อมูล|ประเมินไว|รายการแบบไหน|ต้องเตรียมอะไรบ้าง|ต้องส่งอะไร)/.test(text)) return 'send-info';
  if (/(ล้างข้อมูล|รีเซ็ต|reset|icloud|apple id|find my|google account|google account|frp|activation lock|unpair|ออกจากบัญชี)/.test(text)) return 'account';
  if (/(ขายได้ไหม|ประเมินได้ไหม|เปิดไม่ติด|มีรอย|แบตเสื่อม|เสีย|ขาดอุปกรณ์|ยังขายได้ไหม)/.test(text)) return 'still-possible';
  if (/(ราคา|มีผลกับราคา|ต่างกันยังไง|gps|cellular|wifi|lte|5g|gen 1|gen 2|รุ่นย่อย|จำนวนชัตเตอร์|cycle count|battery health|face id)/.test(text)) return 'pricing';
  if (/(จำนวนมาก|หลายชิ้น|หลายรายการ|รับซื้อจำนวนมากไหม|เหมา|ล็อต)/.test(text)) return 'bulk';
  return 'general';
}

function getFaqThemeListByIntent(intent, context) {
  if (intent === 'send-info') return context.profile.firstMessage;
  if (intent === 'account') return context.checklistItems;
  if (intent === 'still-possible') return context.profile.stillPossible;
  if (intent === 'pricing') return context.profile.priceFactors;
  if (intent === 'bulk') return context.profile.firstMessage;
  return [];
}

function buildFaqFollowUpParagraph(context, question, intent) {
  if (intent === 'send-info') {
    return `คำถามเรื่อง “${question}” เป็นจุดเชื่อมจากการอ่านบทความไปสู่การลงมือจริงโดยตรง เพราะถ้าข้อมูลชุดแรกครบพอ การประเมินจะใกล้เคียงขึ้นและลดการถามกลับหลายรอบ โดยเฉพาะกับเคส ${context.focusTopic} ที่มีตัวแปรมากกว่าหนึ่งจุด`;
  }

  if (intent === 'account') {
    return `ประเด็น “${question}” กระทบทั้งความปลอดภัยของข้อมูลและความลื่นของวันส่งมอบ ถ้าจัดการเรื่องบัญชี การรีเซ็ต หรือการล้างข้อมูลให้ชัดตั้งแต่ต้น งานจะจบง่ายกว่าการปล่อยให้ไปแก้ปัญหาตอนใกล้นัดหรือหน้างานจริง`;
  }

  if (intent === 'still-possible') {
    return `คำถามแบบ “${question}” มักเป็นจุดที่คนขายลังเลมากที่สุด เพราะไม่แน่ใจว่าเคสของตัวเองยังคุยต่อได้หรือไม่ การตอบให้ชัดในบทความช่วยคัดกรองได้ดีว่าควรส่งข้อมูลเพิ่มตรงไหนก่อน และช่วยให้คนอ่านไม่หยุดแค่เพราะมีตำหนิหรืออาการบางจุด`;
  }

  if (intent === 'pricing') {
    return `คำถามเรื่อง “${question}” มักเกี่ยวข้องกับตัวแปรที่ทำให้ช่วงราคาขยับ แม้สินค้าจะดูคล้ายกันภายนอก แต่รายละเอียดเล็ก ๆ อย่างรุ่นย่อย การเชื่อมต่อ แบต หรืออุปกรณ์ร่วมชุด ทำให้การประเมินแตกต่างกันได้พอสมควร`;
  }

  if (intent === 'bulk') {
    return `เมื่อคำถามแตะเรื่อง “${question}” แปลว่าผู้อ่านมักไม่ได้ขายของชิ้นเดียว แต่กำลังคิดถึงภาพรวมของทั้งล็อต การแยกรายการ รุ่น สภาพ และเงื่อนไขนัดให้ชัดตั้งแต่ต้น จะช่วยให้คุยงานเร็วขึ้นกว่าการส่งข้อมูลปนกันทั้งหมด`;
  }

  return `ประเด็น “${question}” เป็นคำถามที่คนอ่านมักอยากได้คำตอบเพิ่มหลังอ่านบทความหลัก เพราะมันช่วยเปลี่ยนจากความเข้าใจแบบกว้าง ๆ ไปสู่การตัดสินใจที่ใช้ได้จริงกับเคสของตัวเองมากขึ้น`;
}

