import { getAreaCoverageProfile } from './areaCoverageProfiles';
import { getAreaEditorialProfile } from './areaEditorialProfiles';

export type AreaFaqItem = {
  question: string;
  answer: string;
};

export type AreaServiceSignal = {
  title: string;
  body: string;
};

const joinThaiList = (items: string[]) => {
  if (items.length === 0) return '';
  if (items.length === 1) return items[0];
  if (items.length === 2) return `${items[0]} และ ${items[1]}`;
  return `${items.slice(0, -1).join(', ')} และ ${items.at(-1)}`;
};

export function buildAreaFaqItems(areaId: string, provinceName: string): AreaFaqItem[] {
  const coverage = getAreaCoverageProfile(areaId);
  const coverageLead = coverage ? joinThaiList(coverage.districts.slice(0, 4)) : '';

  return [
    {
      question: `อยู่ต่างอำเภอใน ${provinceName} ยังเริ่มประเมินได้ไหม`,
      answer: coverage
        ? `ได้ จุดสำคัญคือเริ่มจากการส่งข้อมูลสินค้าให้ครบก่อน แล้วค่อยตามด้วยพื้นที่จริงของคุณ เช่น ${coverageLead} หรือจุดนัดที่สะดวก วิธีนี้ช่วยให้ทีมงานตอบได้ทั้งแนวราคาและขั้นตอนถัดไปในคำตอบเดียว โดยเฉพาะคนที่ไม่ได้อยู่ในตัวเมืองตลอดเวลาหรือยังไม่พร้อมกำหนดวันส่งมอบทันที`
        : `ได้ การเริ่มจากการส่งรูป รุ่น สภาพ และพื้นที่โดยประมาณยังช่วยให้ทีมงานประเมินเคสได้ใกล้เคียงกว่าเดิมมาก แม้คุณจะยังไม่พร้อมระบุวันนัดจริงในรอบแรก`
    },
    {
      question: `ถ้ามีหลายชิ้นจากร้านหรือสำนักงานใน ${provinceName} ควรส่งแบบไหน`,
      answer: `แนะนำให้สรุปเป็นชุดก่อน เช่น หมวดสินค้า จำนวน รุ่นหลัก และอาการเด่นของแต่ละกลุ่ม แล้วค่อยแนบรูปตัวอย่างประกอบ แนวทางนี้เหมาะกับบริบทของ ${provinceName} มาก เพราะช่วยให้การคุยงานไม่กระโดดข้ามรายละเอียด และทำให้ทีมงานวางลำดับประเมินได้ง่ายกว่าการส่งรูปกระจัดกระจายทีละเครื่อง`
    },
    {
      question: `เครื่องมีตำหนิหรือเคยซ่อมใน ${provinceName} ยังส่งประเมินได้ไหม`,
      answer: `ได้ และควรแจ้งตามจริงตั้งแต่ต้นด้วยซ้ำ เพราะข้อมูลพวกจอมีรอย แบตเสื่อม พอร์ตหลวม หรือประวัติซ่อม คือสิ่งที่ช่วยให้ช่วงราคาที่ตอบกลับใกล้เคียงความจริงมากขึ้น ถ้าปกปิดไว้ก่อน คำตอบแรกอาจใช้งานไม่ได้จริงเมื่อถึงขั้นตรวจสภาพหรือคุยรายละเอียดต่อ`
    },
    {
      question: `ข้อความแรกจาก ${provinceName} ควรมีอะไรเพื่อให้ตอบไว`,
      answer: `ให้เริ่มจากรุ่น สภาพ ตำหนิ อุปกรณ์ที่มี และพื้นที่ที่สะดวกคุยงาน จากนั้นเพิ่มรายละเอียดตามประเภทเคสของตัวเอง เช่น ถ้าเป็นงานหลายชิ้นให้สรุปจำนวนคร่าว ๆ หรือถ้าเป็นเครื่องใช้งานส่วนตัวให้บอกอาการที่กระทบการใช้งานจริงก่อน ข้อความที่ครบตั้งแต่ต้นมักช่วยลดการถามย้อนหลายรอบได้มากที่สุด`
    }
  ];
}

export function buildAreaServiceSignals(areaId: string, provinceName: string): AreaServiceSignal[] {
  const coverage = getAreaCoverageProfile(areaId);
  const profile = getAreaEditorialProfile(areaId);
  const coverageLead = coverage ? joinThaiList(coverage.districts.slice(0, 4)) : `โซนต่าง ๆ ใน ${provinceName}`;

  return [
    {
      title: `เช็กราคาได้คมขึ้น เมื่อบอกรุ่นและสภาพจริงของ ${provinceName}`,
      body: `คนขายใน ${provinceName} มักตัดสินใจได้ไวขึ้นเมื่อคำตอบแรกอิงจากข้อมูลจริงของเครื่อง เช่น รุ่น สเปก ความจุ ตำหนิ อาการใช้งาน และอุปกรณ์ในชุด มากกว่าการถามราคาแบบกว้าง ๆ เพราะยิ่งข้อมูลครบ ช่วงราคาที่ตอบกลับก็ยิ่งใช้งานได้จริงกว่าเดิม`
    },
    {
      title: `บอกอำเภอหรือจุดนัดตั้งแต่ต้น ช่วยให้คุยงานต่อได้ง่าย`,
      body: coverage
        ? `ข้อมูลเรื่องพื้นที่อย่าง ${coverageLead} ช่วยให้ทีมงานตอบเรื่องขั้นตอนถัดไปได้ใกล้เคียงสถานการณ์จริงมากขึ้น โดยเฉพาะคนที่ไม่ได้อยู่ในตัวเมืองตลอดหรือยังต้องดูเรื่องความสะดวกของคิวและการส่งมอบควบคู่ไปด้วย`
        : `แม้การประเมินราคาจะยึดจากตัวสินค้าเป็นหลัก แต่การแจ้งพื้นที่จริงตั้งแต่ต้นยังช่วยให้คำตอบเรื่องคิวและจังหวะงานชัดขึ้นมาก โดยเฉพาะเคสที่ยังไม่พร้อมกำหนดวันนัดในรอบแรก`
    },
    {
      title: `งานหลายชิ้นจากร้านหรือสำนักงานใน ${provinceName} ควรสรุปเป็นกลุ่ม`,
      body: profile
        ? `${profile.routeNote} การแยกรายการเป็นหมวด จำนวน และอาการหลักของแต่ละกลุ่มก่อนส่งรูป จะช่วยให้ทั้งคนขายและทีมงานเห็นภาพเดียวกันเร็วขึ้น และลดโอกาสตกหล่นของข้อมูลสำคัญระหว่างคุยงาน`
        : `การสรุปรายการเป็นกลุ่มก่อน เช่น หมวดสินค้า จำนวน รุ่นหลัก และอาการเด่นของแต่ละชุด ช่วยให้ประเมินได้เป็นระบบกว่าการส่งรูปกระจัดกระจายทีละเครื่องมาก`
    },
    {
      title: `หลังดูหน้าจังหวัดแล้ว ควรไปต่อที่หน้าหมวดและคู่มือ`,
      body: `หน้าจังหวัดควรช่วยให้คนใน ${provinceName} รู้ว่าจะเริ่มขายอย่างไร จากนั้นพาไปต่อยังหน้าหมวดสินค้าที่ตรงกับของที่กำลังขาย หรือหน้าคู่มือเตรียมข้อมูลก่อนขาย เพื่อให้ข้อความแรกครบขึ้นและลดเวลาการถามย้อน`
    }
  ];
}
