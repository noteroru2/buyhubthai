export function buildComboEditorialSections(productName: string, provinceName: string): EditorialSection[] {
  const province = provinceProfiles[provinceName] ?? getProvinceProfileWithFallback(provinceName);
  const product = productProfiles[productName];
  const comboSection = provinceProductSections[`${productName}:${provinceName}`];
  const productUsesLeadingSpace = /^[A-Za-z0-9]/.test(productName);
  const withProduct = (prefix: string) => `${prefix}${productUsesLeadingSpace ? ' ' : ''}${productName}`;
  const contextSellProductText = withProduct('บริบทการขาย');
  const evaluateProductText = withProduct('เวลาประเมิน');
  const wantSellProductText = withProduct('ถ้าต้องการขาย');
  const assessmentProductText = withProduct('การประเมิน');

  if (!province || !product) return [];

  return [
    {
      heading: `${contextSellProductText} ใน ${provinceName} ต่างจากหน้ากลางอย่างไร`,
      paragraphs: [
        `สำหรับผู้ขายใน ${provinceName} ${province.localEconomy}`,
        province.travelNote,
        province.geoIntent
      ],
      list: province.sellerTypes
    },
    {
      heading: `${evaluateProductText} ทีม BuyHub จะดูอะไรเป็นพิเศษ`,
      paragraphs: [product.distinguishingCopy, product.prepNote],
      list: product.auditPoints,
      note: product.bundleAngle
    },
    {
      heading: `${wantSellProductText} ใน ${provinceName} ให้คุยงานลื่นขึ้น ควรจัดข้อความแรกแบบไหน`,
      paragraphs: [
        `วิธีที่ช่วยให้${assessmentProductText} ใน ${provinceName} เดินหน้าได้เร็ว คือเริ่มจาก ${product.firstMessageLead.toLowerCase()} แล้วตามด้วยข้อมูลพื้นที่ที่สะดวก เช่น อำเภอหรือจุดนัดโดยประมาณ เพราะหน้าประเภทนี้ไม่ได้มีหน้าที่แค่ตอบว่ารับซื้อหรือไม่ แต่ต้องช่วยให้คนค้นหาก้าวจากการหาข้อมูลไปสู่การเริ่มประเมินจริงได้ทันที`,
        `เมื่อรวมข้อมูลสินค้าตามจุดที่ตลาด ${productName} ให้ความสำคัญเข้ากับข้อมูลพื้นที่จริงใน ${provinceName} ทีมงานจะตอบได้ทั้งเรื่องแนวราคาและรูปแบบการคุยขั้นถัดไปโดยไม่ต้องย้อนถามหลายรอบ ซึ่งช่วยทั้งประสบการณ์ผู้ใช้และความแตกต่างเชิง SEO ของหน้าจังหวัดได้ชัดเจนขึ้น`
      ],
      list: province.handoffChecklist
    },
    ...(comboSection ? [comboSection] : [])
  ];
}

export function getSellEditorialSections(slug: string): EditorialSection[] {
  const normalizedSlug = slug.replace(/^\/+/, '');
  const fallbackSlug = normalizedSlug.startsWith('รับซื้อ-')
    ? normalizedSlug.replace(/^รับซื้อ-/, '')
    : normalizedSlug.startsWith('sell/')
      ? normalizedSlug.replace(/^sell\//, '')
      : normalizedSlug;

  return sellSectionsBySlug[normalizedSlug] ?? sellSectionsBySlug[fallbackSlug] ?? [];
}
