/** Normalize keyword from SEO_KEYWORDS to profile key used above. */
function profileKey(keyword: string): string {
  // Prefer exact keys from PROFILES; also try title-cased tech tokens already used as keys.
  if (PROFILES[keyword]) return keyword;
  const entries = Object.keys(PROFILES);
  const lower = keyword.toLowerCase();
  for (const k of entries) {
    if (k.toLowerCase() === lower) return k;
  }
  // Fuzzy: strip extra spaces
  const compact = keyword.replace(/\s+/g, ' ').trim();
  for (const k of entries) {
    if (k.replace(/\s+/g, ' ').toLowerCase() === compact.toLowerCase()) return k;
  }
  return keyword;
}

export function getSeoSlugHubEnrichment(keyword: string): SeoSlugHubEnrichment | null {
  const key = profileKey(keyword);
  const factory = PROFILES[key];
  if (factory) return factory();

  // Fallback: try matching by slug-like equality against known keywords in PROFILES
  const slugish = keyword.toLowerCase().replace(/\s+/g, '-');
  for (const [k, fn] of Object.entries(PROFILES)) {
    const ks = k.toLowerCase().replace(/\s+/g, '-');
    if (ks === slugish) return fn();
  }
  return null;
}

export function listEnrichedKeywords(): string[] {
  return Object.keys(PROFILES);
}
