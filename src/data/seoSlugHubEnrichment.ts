/**
 * Entity-specific enrichment for indexable seoSlug KEEP hubs.
 * Facts are general evaluation knowledge only — no invented prices/reviews/stats.
 */
export type HubFaq = { question: string; answer: string };
export type HubLongSection = {
  heading: string;
  paragraphs: string[];
  bullets?: string[];
};

export type SeoSlugHubEnrichment = {
  title: string;
  description: string;
  h1: string;
  intro: string[];
  whatWeBuy: string[];
  pricingFactors: string[];
  howToSend: string[];
  faqs: HubFaq[];
  longContentSections: HubLongSection[];
  relatedHubs?: { href: string; label: string }[];
};

type Profile = {
  entity: string;
  intentAngle: string;
  checks: string[];
  buyTypes: string[];
  prepare: string[];
  differFromParent: string;
  faqExtra?: HubFaq;
  relatedHubs?: { href: string; label: string }[];
};

function build(keyword: string, p: Profile, parentLabel: string): SeoSlugHubEnrichment {
  return {
    title: `${keyword} ${p.intentAngle} | BuyHub`,
    description: `บริการ ${keyword} เน้น${p.intentAngle} ประเมินจากรูปและรายละเอียดที่ส่งมา แจ้งแนวราคาก่อนตัดสินใจขาย ติดต่อ LINE @buyhub`,
    h1: `${keyword} — ${p.intentAngle}`,
    intro: [
      `หน้านี้เจาะบริการ **${keyword}** โดยเน้น${p.intentAngle} ไม่ใช่หน้าบริการรับซื้อทั่วไป`,
      `ต่างจาก${parentLabel}ตรงที่${p.differFromParent}`,
      `ส่งรูปและรายละเอียดผ่าน LINE @buyhub เพื่อรับราคาประเมินเบื้องต้นก่อนตัดสินใจขาย ไม่มีค่าใช้จ่ายแอบแฝง`
    ],
    whatWeBuy: p.buyTypes.map((t) => t.includes(keyword) ? t : `${t}`),
    pricingFactors: p.checks,
    howToSend: p.prepare,
    faqs: [
      {
        question: `บริการ ${keyword} ประเมินราคาฟรีไหม?`,
        answer: 'ประเมินราคาฟรี ไม่มีค่าใช้จ่าย เพียงส่งรูปและรายละเอียดผ่าน LINE @buyhub'
      },
      p.faqExtra || {
        question: `ควรเตรียมอะไรก่อนขาย${p.entity}?`,
        answer: `เตรียมข้อมูลรุ่น/สเปกที่เกี่ยวข้อง ถ่ายรูปสภาพชัด และแจ้งอุปกรณ์เสริมที่มีในชุด เพื่อให้ประเมินใกล้เคียงหน้างาน`
      }
    ],
    longContentSections: [
      {
        heading: `จุดตรวจสำคัญเมื่อประเมิน${p.entity}`,
        paragraphs: [
          `ก่อนส่งประเมิน ${keyword} ควรรู้ว่าปัจจัยด้านล่างมีผลต่อแนวราคามากกว่าคำอธิบายทั่วไป`
        ],
        bullets: p.checks
      },
      {
        heading: `ข้อมูลที่ช่วยให้ประเมิน${p.entity}ได้เร็วขึ้น`,
        paragraphs: [
          `ยิ่งส่งข้อมูลเฉพาะของ${p.entity}ครบ ทีมงานยิ่งแจ้งแนวราคาได้ตรงกว่าการส่งเฉพาะรูปด้านนอก`
        ],
        bullets: p.prepare
      }
    ],
    relatedHubs: p.relatedHubs
  };
}

